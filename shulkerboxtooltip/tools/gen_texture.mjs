// Turns ShulkerBoxTooltip's `shulker_box_tooltip.png` (MIT, MisterPeModder) into
// `mixins/shulkerboxtooltip/texture.rs`: a `.hnmod` carries no PNGs, so the pixels are compiled in.
//   node tools/gen_texture.mjs <path to shulker_box_tooltip.png>
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2];
const png = fs.readFileSync(src);
if (png.readUInt32BE(0) !== 0x89504e47) throw new Error("not a PNG");
let off = 8, width = 0, height = 0, depth = 0, ctype = 0, palette = null, trns = null;
const idat = [];
while (off < png.length) {
  const len = png.readUInt32BE(off);
  const type = png.toString("ascii", off + 4, off + 8);
  const data = png.subarray(off + 8, off + 8 + len);
  if (type === "IHDR") {
    width = data.readUInt32BE(0); height = data.readUInt32BE(4); depth = data[8]; ctype = data[9];
    if (data[12] !== 0) throw new Error("interlaced PNG not supported");
  } else if (type === "PLTE") palette = data;
  else if (type === "tRNS") trns = data;
  else if (type === "IDAT") idat.push(data);
  off += 12 + len;
}
if (depth !== 8) throw new Error("bit depth " + depth + " not supported");
const channels = { 0: 1, 2: 3, 3: 1, 4: 2, 6: 4 }[ctype];
const raw = zlib.inflateSync(Buffer.concat(idat));
const stride = width * channels;
const pixels = Buffer.alloc(width * height * channels);
let prev = Buffer.alloc(stride);
for (let y = 0; y < height; y++) {
  const f = raw[y * (stride + 1)];
  const line = Buffer.from(raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1)));
  for (let x = 0; x < stride; x++) {
    const a = x >= channels ? line[x - channels] : 0, b = prev[x], c = x >= channels ? prev[x - channels] : 0;
    let v = line[x];
    if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
    else if (f === 4) { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
    line[x] = v & 0xff;
  }
  line.copy(pixels, y * stride);
  prev = line;
}
const rgba = Buffer.alloc(width * height * 4);
for (let i = 0; i < width * height; i++) {
  let r, g, b, al = 255;
  if (ctype === 6) [r, g, b, al] = pixels.subarray(i * 4, i * 4 + 4);
  else if (ctype === 2) [r, g, b] = pixels.subarray(i * 3, i * 3 + 3);
  else if (ctype === 0) r = g = b = pixels[i];
  else if (ctype === 4) { r = g = b = pixels[i * 2]; al = pixels[i * 2 + 1]; }
  else if (ctype === 3) { const p = pixels[i]; [r, g, b] = palette.subarray(p * 3, p * 3 + 3); al = trns && p < trns.length ? trns[p] : 255; }
  rgba.set([r, g, b, al], i * 4);
}
const rows = [];
for (let y = 0; y < height; y++) {
  rows.push("    " + Array.from(rgba.subarray(y * width * 4, (y + 1) * width * 4)).join(", ") + ",");
}
const out = `// Generated by tools/gen_texture.mjs from ShulkerBoxTooltip's
// assets/shulkerboxtooltip/textures/gui/sprites/shulker_box_tooltip.png
// (ShulkerBoxTooltip by MisterPeModder, MIT licence). Do not edit by hand.
// Nine-slice sprite: ${width}x${height}, border 7, inner tiled (its .mcmeta).

pub const WIDTH: u32 = ${width};
pub const HEIGHT: u32 = ${height};
pub const BORDER: u32 = 7;
/// RGBA, row by row.
pub static RGBA: [u8; ${width * height * 4}] = [
${rows.join("\n")}
];
`;
const dest = path.join(root, "mixins", "shulkerboxtooltip", "texture.rs");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(JSON.stringify({ width, height, ctype, dest, bytes: rgba.length }));
